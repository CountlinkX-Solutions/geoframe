#[test]
fn offset_curve_takes_a_distance_per_row_and_keeps_nulls_and_crs() {
    let c = GeoColumn::from_wkt(
        &[
            Some("LINESTRING (0 0, 10 0)"),
            Some("LINESTRING (0 0, 10 0)"),
            None,
            Some("LINESTRING (0 0, 10 0)"),
        ],
        Some("EPSG:4326"),
    )
    .unwrap();
    let out = c
        .offset_curve(
            &[Some(1.0), Some(-2.0), Some(1.0), None],
            &params("round", 8),
        )
        .unwrap();
    let text = out.to_wkt().unwrap();
    assert_eq!(text[0].as_deref(), Some("LINESTRING(0 1,10 1)"));
    assert_eq!(text[1].as_deref(), Some("LINESTRING(0 -2,10 -2)"));
    assert_eq!(text[2], None);
    assert_eq!(text[3], None);
    assert_eq!(out.crs().as_deref(), Some("EPSG:4326"));
}

#[test]
fn offset_curve_of_a_zero_distance_is_the_input_line() {
    let out = offset("LINESTRING (0 0, 3 4, 6 4)", 0.0, "round");
    assert_eq!(
        out.to_wkt().unwrap()[0].as_deref(),
        Some("LINESTRING(0 0,3 4,6 4)")
    );
}

#[test]
fn offset_curve_rejects_bad_parameters() {
    let c = one("LINESTRING (0 0, 1 1)");
    assert!(c.offset_curve(&[Some(1.0)], &params("round", 0)).is_err());
    assert!(c
        .offset_curve(&[Some(1.0)], &params("round", 1_000_000))
        .is_err());
    let bad_mitre = OffsetParams {
        mitre_limit: f64::NAN,
        ..params("mitre", 8)
    };
    assert!(c.offset_curve(&[Some(1.0)], &bad_mitre).is_err());
    assert!(c.offset_curve(&[], &params("round", 8)).is_err());
    assert!(OffsetJoin::parse("rounded").is_err());
}

#[test]
fn offset_curve_caps_the_estimated_vertices() {
    // 1,000 vertices at 10,000 quadrant segments would build over 10,000,000 vertices.
    let coords: Vec<String> = (0..1000).map(|i| format!("{} {}", i, i % 2)).collect();
    let c = one(&format!("LINESTRING ({})", coords.join(", ")));
    assert!(c
        .offset_curve(&[Some(0.1)], &params("round", 10_000))
        .is_err());
}

#[test]
fn offset_curve_non_finite_distance_or_coordinates_give_null() {
    let c = one("LINESTRING (0 0, 1 1)");
    let out = c
        .offset_curve(&[Some(f64::NAN)], &params("round", 8))
        .unwrap();
    assert_eq!(out.to_wkt().unwrap(), vec![None]);
    let out = c
        .offset_curve(&[Some(f64::INFINITY)], &params("round", 8))
        .unwrap();
    assert_eq!(out.to_wkt().unwrap(), vec![None]);
}

#[test]
fn offset_curve_a_long_line_is_fast() {
    // 20,000 vertices on a gentle wave: the cutting must use the spatial index.
    let coords: Vec<String> = (0..20_000)
        .map(|i| format!("{} {}", f64::from(i), f64::from(i % 7) * 0.3))
        .collect();
    let c = one(&format!("LINESTRING ({})", coords.join(", ")));
    let out = c.offset_curve(&[Some(0.5)], &params("round", 8)).unwrap();
    assert!(out.length()[0].unwrap() > 19_000.0);
}

#[test]
fn offset_curve_of_a_closed_line_with_mitre_keeps_its_end_pieces() {
    // GEOS answers LINESTRING (5 -1, 5 5, -1 5) here; the pieces next to the (unjoined) start
    // of the closed line are kept.
    let out = offset("LINESTRING (0 0, 4 0, 4 4, 0 4, 0 0)", -1.0, "mitre");
    assert_eq!(
        out.to_wkt().unwrap()[0].as_deref(),
        Some("LINESTRING(0 -1,5 -1,5 5,-1 5,-1 0)")
    );
}
