//! `offset_curve`: expected answers come from Shapely 2.2 / GEOS 3.14 (`quad_segs` 8).

use crate::{GeoColumn, OffsetJoin, OffsetParams};

fn col(rows: &[Option<&str>]) -> GeoColumn {
    GeoColumn::from_wkt(rows, None).expect("valid WKT")
}

fn one(wkt: &str) -> GeoColumn {
    col(&[Some(wkt)])
}

fn params(join: &str, quad_segs: u32) -> OffsetParams {
    OffsetParams {
        quad_segs,
        join: OffsetJoin::parse(join).unwrap(),
        mitre_limit: 5.0,
    }
}

fn offset(wkt: &str, d: f64, join: &str) -> GeoColumn {
    one(wkt).offset_curve(&[Some(d)], &params(join, 8)).unwrap()
}

/// Same curve: equal length and within 1e-6 of each other (Hausdorff, both ways).
fn same_curve(got: &GeoColumn, want: &GeoColumn, what: &str) -> Result<(), String> {
    let (g, w) = (got.to_wkt().unwrap(), want.to_wkt().unwrap());
    if g == w {
        return Ok(());
    }
    let empty = |c: &GeoColumn| {
        c.to_wkt().unwrap()[0]
            .as_deref()
            .is_some_and(|t| t.contains("EMPTY"))
    };
    if empty(got) != empty(want) {
        return Err(format!("{what}: emptiness\n got {g:?}\nwant {w:?}"));
    }
    if empty(got) {
        return Ok(());
    }
    let (lg, lw) = (got.length()[0].unwrap(), want.length()[0].unwrap());
    if (lg - lw).abs() > 1e-6 * lw.max(1.0) {
        return Err(format!(
            "{what}: length {lg} != {lw}\n got {g:?}\nwant {w:?}"
        ));
    }
    let h = got.hausdorff_distance(want, None).unwrap()[0].unwrap();
    if h > 1e-6 {
        return Err(format!("{what}: hausdorff {h}\n got {g:?}\nwant {w:?}"));
    }
    Ok(())
}

