#[test]
fn esri_projection_names_reproject_like_pyproj() {
    // forward to 1e-3 projected units, inverse to 1e-8 degrees; every failure is reported
    let mut failures = Vec::new();
    for (name, wkt, points) in CASES {
        // proj4rs inverts the ellipsoidal Cassini-Soldner series to 2e-7 degrees (2 cm), the same
        // for EPSG:2066 itself; the forward projection agrees to 1e-5 m.
        let inverse = if *name == "EPSG:2066" { 1e-6 } else { 1e-8 };
        for (lon, lat, x, y, back_lon, back_lat) in points {
            match transform_xy("EPSG:4326", wkt, *lon, *lat) {
                Err(e) => failures.push(format!("{name} forward at {lon} {lat}: {e}")),
                Ok((gx, gy)) if (gx - x).abs() >= 1e-3 || (gy - y).abs() >= 1e-3 => {
                    failures.push(format!("{name} forward: {gx} {gy} vs {x} {y}"));
                }
                Ok(_) => {}
            }
            match transform_xy(wkt, "EPSG:4326", *x, *y) {
                Err(e) => failures.push(format!("{name} inverse at {x} {y}: {e}")),
                Ok((bx, by))
                    if (bx - back_lon).abs() >= inverse || (by - back_lat).abs() >= inverse =>
                {
                    failures.push(format!(
                        "{name} inverse: {bx} {by} vs {back_lon} {back_lat}"
                    ));
                }
                Ok(_) => {}
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
